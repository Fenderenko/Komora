"""Mouse battery tables for Komora from two open projects (MIT):

    python tools/gen_mice.py <razer catalog.rs> <steel-mouse devices.rs>

- Razer: crates/razer-hid/src/catalog.rs of github.com/xzeldon/razer-battery-report — product id, name, transaction id,
  interface, the wait between request and answer, whether charging can be asked.
- SteelSeries: src/protocol/devices.rs of github.com/yurtemre7/steel-mouse — product id, name, interface, the kind of
  battery request.
Writes src/mice_table.rs.
"""

import pathlib
import re
import sys


def main():
    rz = open(sys.argv[1], encoding='utf-8').read()
    ss = open(sys.argv[2], encoding='utf-8').read()
    out = ['// Generated by tools/gen_mice.py from razer-battery-report and steel-mouse (MIT) — do not edit by hand.', '']
    out.append('/// Razer: (product id, name, transaction id, interface, wait µs, charging can be asked).')
    out.append('pub const RAZER: &[(u16, &str, u8, u8, u32, bool)] = &[')
    n = 0
    for m in re.finditer(r'Entry \{ pid: (0x[0-9A-Fa-f]+), name: "([^"]+)", tid: (0x[0-9A-Fa-f]+), interface: (\d+), wait_us: ([\d_]+), charging: Support::(\w+)', rz):
        out.append(f'    ({m.group(1).lower()}, "{m.group(2)}", {m.group(3).lower()}, {m.group(4)}, {m.group(5)}, {"true" if m.group(6) == "Query" else "false"}),')
        n += 1
    out.append('];')
    out.append('')
    out.append('/// SteelSeries mice: (product id, name, interface, request: 0x92 / 0xD2 — Aerox and Prime, 0xAA — Rival 3 Wireless and 650; level: 21 steps or direct percent).')
    out.append('pub const STEELSERIES: &[(u16, &str, u8, u8, bool)] = &[')
    k = 0
    for m in re.finditer(r'\(0x1038, (0x[0-9a-fA-F]+)\) => Some\(MouseProfile \{\s*name: "([^"]+)",.*?endpoint: (\d+),\s*battery_kind: (Some\(BatteryKind::(\w+)(?: \{ command: (0x[0-9A-Fa-f]+) \})?\)|None)', ss, re.S):
        if m.group(4) == 'None':
            continue
        kind, cmd = m.group(5), m.group(6)
        req = {'AeroxPrime': cmd, 'DirectAerox': cmd, 'Rival3Or650': '0xAA'}.get(kind)
        if not req:
            continue
        name = m.group(2).replace('SteelSeries ', '')
        out.append(f'    ({m.group(1).lower()}, "{name}", {m.group(3)}, {req.lower()}, {"true" if kind != "AeroxPrime" else "false"}),')
        k += 1
    out.append('];')
    p = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'mice_table.rs'
    p.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print(f'razer {n}, steelseries {k}')


if __name__ == '__main__':
    main()
