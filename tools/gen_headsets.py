"""Headset battery table for Komora from Arcmix's web/devices.json (descriptions ported from Linux-Arctis-Manager).

    python tools/gen_headsets.py <path to Arcmix web/devices.json>

Writes src/headsets_table.rs: for every headset whose description reads a battery level — its product ids, the HID
interface and collection, the request, what the answer starts with, where the level, charging and connection sit.
Quirks Arcmix verified on real devices (engine::quirks) are applied here too.
"""

import json
import pathlib
import sys

SIZES = {'uint8': 1, 'int8': 1, 'uint16': 2, 'int16': 2, 'uint32': 4, 'float32': 4}
# interface numbers Arcmix found on real receivers (the descriptions say otherwise)
IFACE = {'SteelSeries Arctis 7': 5, 'SteelSeries Arctis 9': 0}


def offsets(fields):
    out, at = {}, 0
    for f in fields:
        out[f['name']] = (at, f)
        at += SIZES.get(f.get('type', 'uint8'), 1)
    return out


def level_map(dev, tname):
    t = dev.get('transforms', {}).get(tname or '', {})
    if t.get('type') == 'case_int_to_int':
        return sorted((int(k), int(v)) for k, v in t['values'].items())
    return None


def labels(dev, tname, good):
    t = dev.get('transforms', {}).get(tname or '', {})
    return sorted(int(k) for k, v in t.get('values', {}).items() if good(v))


def main():
    src = json.load(open(sys.argv[1], encoding='utf-8'))
    rows = []
    for dev in src:
        d = dev['device']
        reads = dev.get('sync_read') or []
        for r in reads:
            st = dev['structs'].get(r['struct'])
            if not isinstance(st, dict) or 'incoming' not in st:
                continue
            maps = {m.get('emit'): m for m in r.get('maps', [])}
            b = maps.get('battery_changed')
            if not b or 'field' not in b:
                continue
            inc = offsets(st['incoming'])
            if b['field'] not in inc:
                continue
            req = [f['constant'] for f in st['outgoing'] if 'constant' in f]
            if len(req) != len(st['outgoing']):
                continue
            match = [(at, f['constant']) for at, f in inc.values() if 'constant' in f]
            batt_at, bf = inc[b['field']]
            lmap = level_map(dev, b.get('transform'))
            lo, hi = (bf.get('range') or [0, 100])[:2]
            ch = maps.get('charging_changed')
            charge = None
            if ch and ch.get('field') in inc:
                vals = labels(dev, ch.get('transform'), lambda v: 'CHARGING' in str(v) and 'NOT_CHARGING' not in str(v) and 'DISCHARGING' not in str(v))
                if vals:
                    charge = (inc[ch['field']][0], vals)
            cn = maps.get('connection_changed')
            conn = None
            if cn and cn.get('field') in inc:
                vals = labels(dev, cn.get('transform'), lambda v: str(v).endswith('CONNECTED') and 'NOT_CONNECTED' not in str(v) and 'DISCONNECTED' not in str(v))
                if vals:
                    conn = (inc[cn['field']][0], vals)
            hid = d.get('hid', {})
            iface = IFACE.get(d['name'], (hid.get('command_interface') or {}).get('interface', 0))
            pids = [(v['product_id'], v.get('name', d['name'])) for v in d.get('variants', [])]
            rows.append(dict(name=d['name'], vid=d['vendor_id'], pids=pids, iface=iface, page=hid.get('usage_page', 0), usage=hid.get('usage', 0),
                             req=req, match=match, batt=batt_at, lo=lo, hi=hi, lmap=lmap, charge=charge, conn=conn))
            break
    rs = ['// Generated by tools/gen_headsets.py from Arcmix web/devices.json — do not edit by hand.', '',
          'use crate::headsets::Hs;', '', 'pub const HEADSETS: &[Hs] = &[']
    for r in rows:
        pids = ', '.join(f'(0x{p:04x}, {json.dumps(n.replace("SteelSeries ", ""))})' for p, n in r['pids'])
        lmap = 'None' if not r['lmap'] else 'Some(&[' + ', '.join(f'({a}, {b})' for a, b in r['lmap']) + '])'
        ch = 'None' if not r['charge'] else f'Some(({r["charge"][0]}, &{r["charge"][1]}))'
        cn = 'None' if not r['conn'] else f'Some(({r["conn"][0]}, &{r["conn"][1]}))'
        rs.append(f'    Hs {{ vid: 0x{r["vid"]:04x}, pids: &[{pids}], iface: {r["iface"]}, page: 0x{r["page"]:04x}, usage: {r["usage"]}, req: &{r["req"]}, '
                  f'expect: &{[list(m) for m in r["match"]]}, batt: {r["batt"]}, range: ({r["lo"]}, {r["hi"]}), levels: {lmap}, charging: {ch}, connected: {cn} }},'.replace('[[', '[(').replace(']]', ')]').replace('], [', '), ('))
    rs.append('];')
    out = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'headsets_table.rs'
    out.write_text('\n'.join(rs) + '\n', encoding='utf-8', newline='\n')
    for r in rows:
        print(f'{r["name"]}: iface {r["iface"]} req {r["req"]} batt@{r["batt"]} {"levels" if r["lmap"] else "range"} {r["lo"]}..{r["hi"]} charge {r["charge"]} conn {r["conn"]}')
    print(len(rows), 'headsets')


if __name__ == '__main__':
    main()
